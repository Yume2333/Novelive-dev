import { chromium } from 'playwright';
const [,,w,h,n] = process.argv;
const b = await chromium.launch();
const p = await (await b.newContext({viewport:{width:+w,height:+h},deviceScaleFactor:1})).newPage();
await p.goto('http://localhost:8777/test2.html');
await p.waitForFunction(()=>document.getElementById('ready').textContent==='1');
await p.evaluate(()=>document.fonts.ready);
await p.evaluate((n)=>window.stepN(+n), n);
await p.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
await p.screenshot({path:`../dom_${w}x${h}_${n}.png`});
console.log('done');
await b.close();
