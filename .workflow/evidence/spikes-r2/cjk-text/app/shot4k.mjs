import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await (await b.newContext({viewport:{width:3840,height:2160},deviceScaleFactor:1})).newPage();
await p.goto('http://localhost:8777/test2.html');
await p.waitForFunction(()=>document.getElementById('ready').textContent==='1');
await p.evaluate(()=>document.fonts.ready);
await p.evaluate(()=>window.all());
await p.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
await p.screenshot({path:'../dom_4k.png'});
console.log('ok');
await b.close();
